import assert from 'node:assert/strict';
import {test} from 'node:test';

test('vault selection updates details without changing the URL and protects unsaved edits', async () => {
  globalThis.window = {};
  globalThis.location = {search: '?id=b'};
  let replaced = '';
  globalThis.history = {state: null, replaceState: (_state, _title, url) => { replaced = url; }};
  const detail = {innerHTML: '', addEventListener() {}, querySelector: () => null};
  const photo = {innerHTML: '', querySelector: () => null};
  const selected = {dataset: {}};
  const form = {dataset: {}};
  const classes = new Set();
  const layout = {classList: {add: value => classes.add(value), remove: value => classes.delete(value)}};
  const rows = ['a', 'b'].map(id => ({dataset: {cardId: id}, setAttribute(_name, value) { this.selected = value; }}));
  let clickHandler;
  const menu = {open: true, contains: target => target === 'inside'};
  const discardButtons = {'[data-discard]': {}, '[data-cancel]': {}};
  const discardDialog = {open: false, querySelector: selector => discardButtons[selector], showModal() { this.open = true; }, close(value) { this.open = false; this.returnValue = value; this.onclose(); }};
  globalThis.document = {querySelector: selector => selector === '.vault-layout' ? layout : selector === '.vault-selected' ? selected : selector === '.vault-menu[open]' ? menu : selector === '.vault-photo-panel' ? photo : detail, querySelectorAll: () => rows, getElementById: id => id === 'discard-changes-dialog' ? discardDialog : form, addEventListener: (_type, handler) => { clickHandler = handler; }, removeEventListener() {}};
  const {vault, initializeVault} = await import('./vault.js');
  const cards = [{id: 'a', name: 'First', certNumber: '00000001', frontImage: '/first.jpg'}, {id: 'b', name: 'Second', certNumber: '00000002', frontImage: '/second.jpg'}];
  vault(cards);
  initializeVault();
  clickHandler({target: 'inside'});
  assert.equal(menu.open, true);
  clickHandler({target: 'outside'});
  assert.equal(menu.open, false);
  assert.equal(replaced, '/vault');
  assert.match(detail.innerHTML, /Second/);
  assert.match(photo.innerHTML, /second.jpg/);
  assert.doesNotMatch(detail.innerHTML, /second.jpg/);
  await window.__selectVault('a');
  assert.match(detail.innerHTML, /First/);
  assert.match(photo.innerHTML, /first.jpg/);
  assert.equal(rows[0].selected, 'true');
  assert.equal(replaced, '/vault');
  form.dataset.dirty = 'true';
  const pending = window.__selectVault('b');
  assert.equal(discardDialog.open, true);
  discardButtons['[data-cancel]'].onclick();
  await pending;
  assert.match(detail.innerHTML, /First/);
  const discard = window.__selectVault('b');
  discardButtons['[data-discard]'].onclick();
  await discard;
  assert.match(detail.innerHTML, /Second/);
  form.dataset.dirty = 'false';
  await window.__selectVault('a');
  form.dataset.dirty = 'true';
  const cancelSelection = window.__selectVault('a');
  discardButtons['[data-cancel]'].onclick();
  await cancelSelection;
  assert.equal(classes.has('is-unselected'), false);
  form.dataset.dirty = 'false';
  await window.__selectVault('a');
  assert.equal(classes.has('is-unselected'), true);
  assert.equal(rows[0].selected, 'false');
  await window.__selectVault('b');
  assert.equal(classes.has('is-unselected'), false);
  assert.equal(rows[1].selected, 'true');
  assert.match(detail.innerHTML, /Second/);
});
